/**
 * Regenerates `packages/creaton-core/test-fixtures/link-device-golden.json`
 * — the cross-language golden fixture whose `p`/`from` the DESKTOP test
 * (`desktop/src-tauri/src/identity_link_tests.rs`
 * `golden_fixture_from_the_typescript_web_code_links_the_account`) must
 * decrypt and link.
 *
 * Everything here is the ACTUAL production code: `@creaton/core/link-device`
 * builders for the payload/redirect and nostr-tools NIP-44 for the crypto —
 * the same stack `buildLinkDeviceRedirect` uses. NIP-44 encrypts with a
 * random per-message nonce, so each run produces a NEW fixture; regenerate
 * only when the wire shape changes, and re-run the Rust test against it.
 *
 * Run from the repo root (or anywhere):
 *   node --experimental-strip-types \
 *     web/src/features/identity/lib/generate-link-device-golden.mjs
 */
import { writeFileSync } from "node:fs";

import { decrypt, encrypt, getConversationKey } from "nostr-tools/nip44";
import { getPublicKey } from "nostr-tools/pure";

import {
  buildLinkDeviceCallback,
  buildLinkDevicePayload,
  decodeBase64Url,
  parseLinkDeviceCallback,
  serializeLinkDevicePayload,
} from "@creaton/core/link-device.ts";

/** Fixed inputs — mirrored by the Rust golden test. */
const ONE_TIME_SK = "02".repeat(32);
const ACCOUNT_SK = "01".repeat(32);
const NONCE = "gZ3kQ9xT2mN7pR4v";
const NOW_MS = 1760000000000;

function hexToBytes(hex) {
  const out = new Uint8Array(32);
  for (let i = 0; i < 32; i += 1) {
    out[i] = Number.parseInt(hex.slice(i * 2, i * 2 + 2), 16);
  }
  return out;
}

const oneTimePub = getPublicKey(hexToBytes(ONE_TIME_SK));
const accountPub = getPublicKey(hexToBytes(ACCOUNT_SK));

const payload = buildLinkDevicePayload({
  secretKeyHex: ACCOUNT_SK,
  nonce: NONCE,
  nowMs: NOW_MS,
});
const plaintext = serializeLinkDevicePayload(payload);
const conversationKey = getConversationKey(hexToBytes(ACCOUNT_SK), oneTimePub);
const ciphertext = encrypt(plaintext, conversationKey);
const url = buildLinkDeviceCallback(
  "creaton://identity",
  ciphertext,
  accountPub,
);

// Self-verify through the same parse path the desktop mirror uses.
const parsed = parseLinkDeviceCallback(new URL(url).search);
if (!parsed.ok)
  throw new Error(`fixture redirect did not parse: ${parsed.error}`);
const recovered = decrypt(
  decodeBase64Url(parsed.value.p),
  getConversationKey(hexToBytes(ONE_TIME_SK), parsed.value.from),
);
if (recovered !== plaintext)
  throw new Error("fixture does not decrypt back to its plaintext");

const fixture = {
  _provenance:
    "Generated by web/src/features/identity/lib/generate-link-device-golden.mjs " +
    "(nostr-tools NIP-44 + packages/creaton-core/src/link-device.ts builders). " +
    "Consumed by golden_fixture_from_the_typescript_web_code_links_the_account " +
    "in desktop/src-tauri/src/identity_link_tests.rs. NIP-44 encryption is " +
    "randomized — this is a captured artifact; regenerate only on wire-shape changes.",
  oneTimeSk: ONE_TIME_SK,
  accountSk: ACCOUNT_SK,
  nonce: NONCE,
  nowMs: NOW_MS,
  exp: payload.exp,
  p: parsed.value.p,
  from: parsed.value.from,
  url,
};

const target = new URL(
  "../../../../../packages/creaton-core/test-fixtures/link-device-golden.json",
  import.meta.url,
);
writeFileSync(target, `${JSON.stringify(fixture, null, 2)}\n`);
console.log(`wrote ${target.pathname}`);
