#!/usr/bin/env node
// Brings the ABIs of the money contracts (contracts/pot) into the shared package, from forge's own build output.
//
//   node scripts/pot-app-abi.mjs                    # rewrite packages/creaton-core/src/pot/abis.generated.ts
//   node scripts/pot-app-abi.mjs --check            # fail when that file is not what the output says
//   node scripts/pot-app-abi.mjs --out <dir>        # read another forge output folder (default contracts/pot/out)
//
// Build the output first with `forge build` in contracts/pot (a throwaway one: `forge build --skip test --skip script
// --out <dir> --cache-path <dir>/cache`). The generated file is never edited by hand: the core test `abi-fresh.test.mjs`
// builds the contracts fresh and fails when the file differs, so a changed contract cannot slip past the app.

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");

/** The contracts whose ABI the app and the shared package use, with the constant each is exported as. */
export const CONTRACTS = [
  { name: "Treasury", constant: "TREASURY_ABI" },
  { name: "TaskBook", constant: "TASK_BOOK_ABI" },
  { name: "Vester", constant: "VESTER_ABI" },
  { name: "Launcher", constant: "LAUNCHER_ABI" },
  { name: "Pair", constant: "PAIR_ABI" },
  { name: "ShareToken", constant: "SHARE_TOKEN_ABI" },
  { name: "PlayDollar", constant: "PLAY_DOLLAR_ABI" },
];

export const GENERATED_FILE = resolve(
  repoRoot,
  "packages/creaton-core/src/pot/abis.generated.ts",
);
export const DEFAULT_OUT = resolve(repoRoot, "contracts/pot/out");

/** Keep what a caller needs to encode, decode and describe a call; drop compiler bookkeeping (`internalType`). */
function clean(value) {
  if (Array.isArray(value)) return value.map(clean);
  if (value && typeof value === "object") {
    const out = {};
    for (const [key, inner] of Object.entries(value)) {
      if (key === "internalType") continue;
      out[key] = clean(inner);
    }
    return out;
  }
  return value;
}

/**
 * Read each contract's ABI from forge's output folder.
 * @param {string} outDir forge's `out` folder
 * @returns {Record<string, unknown[]>} constant name to ABI
 */
export function readAbis(outDir) {
  const abis = {};
  for (const { name, constant } of CONTRACTS) {
    const file = resolve(outDir, `${name}.sol`, `${name}.json`);
    if (!existsSync(file))
      throw new Error(
        `No build output for ${name} at ${file}. Run forge build first.`,
      );
    const abi = JSON.parse(readFileSync(file, "utf8")).abi;
    if (!Array.isArray(abi) || abi.length === 0)
      throw new Error(`${file} holds no ABI.`);
    abis[constant] = clean(abi);
  }
  return abis;
}

/** The text of the generated file for `abis`: one `as const` array per contract, stable, one entry per line. */
export function render(abis) {
  const lines = [
    "// @generated by scripts/pot-app-abi.mjs from the forge output of contracts/pot. Do not edit by hand.",
    "// `abi-fresh.test.mjs` builds the contracts fresh and fails when this file differs from that build.",
    "",
  ];
  for (const { name, constant } of CONTRACTS) {
    lines.push(`/** The ABI of \`contracts/pot/src\`'s ${name}. */`);
    lines.push(`export const ${constant} = [`);
    for (const item of abis[constant]) lines.push(`  ${JSON.stringify(item)},`);
    lines.push("] as const;", "");
  }
  return lines.join("\n");
}

function main() {
  const args = process.argv.slice(2);
  const check = args.includes("--check");
  const outIndex = args.indexOf("--out");
  const outDir = outIndex >= 0 ? resolve(args[outIndex + 1]) : DEFAULT_OUT;
  const text = render(readAbis(outDir));
  if (check) {
    const have = existsSync(GENERATED_FILE)
      ? readFileSync(GENERATED_FILE, "utf8")
      : "";
    if (have !== text) {
      console.error(
        "packages/creaton-core/src/pot/abis.generated.ts is not what the contracts build to. Run: node scripts/pot-app-abi.mjs",
      );
      process.exit(1);
    }
    console.log("pot ABIs are current.");
    return;
  }
  writeFileSync(GENERATED_FILE, text);
  console.log(`wrote ${GENERATED_FILE}`);
}

if (
  process.argv[1] &&
  resolve(process.argv[1]) === fileURLToPath(import.meta.url)
)
  main();
